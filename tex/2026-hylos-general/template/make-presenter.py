#!/usr/bin/env python3
"""Write <job>-presenter.tex: every page of <job>.pdf on the left half of a
double-width page, its speaker notes (from <job>.notes, written by
\\speakernote in dcptalk.sty) on the right. Compile it with LuaLaTeX; present
with `pdfpc -n right`, or read it in any viewer.

In a note, \\\\ separates bullet points and [click] starts the bullets of the
next overlay step. On each page of a frame with overlays, bullets of the
current step are bold, those of later steps grey.

Usage: make-presenter.py JOB
"""
import argparse
import re
import subprocess

SEP = '|||'


def read_notes(job):
    """{page: (title, [raw TeX note, ...])}"""
    pages = {}
    with open(job + '.notes', encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            if not line:
                continue
            page, title, text = line.split(SEP, 2)
            entry = pages.setdefault(int(page.strip()), (title.strip(), []))
            entry[1].append(text.strip())
    return pages


def page_count(job):
    out = subprocess.run(['pdfinfo', job + '.pdf'], capture_output=True,
                         text=True, check=True).stdout
    return int(re.search(r'^Pages:\s+(\d+)', out, re.M).group(1))


def steps(pages, n):
    """{page: (step, of)}: the overlay step of each page within its frame,
    found from runs of consecutive pages with the same title and notes."""
    out, run = {}, []
    for p in range(1, n + 1):
        key = pages.get(p)
        if run and pages.get(run[-1]) == key and key is not None:
            run.append(p)
        else:
            for i, q in enumerate(run):
                out[q] = (i, len(run))
            run = [p]
    for i, q in enumerate(run):
        out[q] = (i, len(run))
    return out


def bullets(text, step, of):
    items, s = [], 0
    for b in (t.strip() for t in text.split('\\\\')):
        if not b:
            continue
        if b.startswith('[click]'):
            s += 1
            b = '\\clickmark{}' + b[len('[click]'):]
        style = ('' if of == 1 else '\\now' if s == step
                 else '\\later' if s > step else '')
        items.append(f'  \\item {style}{{{b}}}')
    return '\\begin{itemize}\n' + '\n'.join(items) + '\n\\end{itemize}'


PREAMBLE = r'''% Generated by make-presenter.py from <<job>>.pdf and <<job>>.notes
\DocumentMetadata{lang = en-GB, tagging = on}
\documentclass[14pt]{extarticle}
\usepackage{graphicx, xcolor, enumitem, geometry}
\usepackage{fontspec}
\setmainfont{Latin Modern Sans}
\setmonofont{JetBrains Mono NL}[Scale = MatchLowercase]
\newsavebox\slide
\sbox\slide{\includegraphics[page = 1]{<<job>>.pdf}}
\geometry{paperwidth = 2\wd\slide, paperheight = \ht\slide, margin = 0pt}
\pagestyle{empty}
\setlength\parindent{0pt}
\setlength\topskip{0pt}
\setlength\parskip{0pt}
\setlist[itemize]{leftmargin = 1.2em, itemsep = .4ex, topsep = .6ex}
\newcommand\code[1]{\texttt{#1}}
\newcommand\now[1]{\textbf{#1}}
\newcommand\later[1]{\textcolor{gray}{#1}}
\newcommand\clickmark{\textcolor{orange!80!black}{$\triangleright$}}
\newcommand\notespage[5]{% page, title, step, of, notes
  \noindent\hbox to \paperwidth{%
  \includegraphics[page = #1, alt = {Slide #1: #2}]{<<job>>.pdf}%
  \hspace{8mm}%
  \begin{minipage}[b][\ht\slide][t]{\dimexpr\wd\slide - 16mm\relax}
    \raggedright
    \vspace{6mm}
    {\Large\bfseries #2\par}
    {\small\color{gray} slide #1 / <<n>>\ifnum#4>1{} \quad step \the\numexpr#3+1\relax{} of #4\fi\par}
    \medskip
    #5
  \end{minipage}\hfil}
  \newpage}
\begin{document}
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('job')
    job = ap.parse_args().job
    pages, n = read_notes(job), page_count(job)
    st = steps(pages, n)
    with open(job + '-presenter.tex', 'w', encoding='utf-8') as f:
        f.write(PREAMBLE.replace('<<job>>', job).replace('<<n>>', str(n)))
        for p in range(1, n + 1):
            title, texts = pages.get(p, ('', []))
            step, of = st[p]
            body = '\n'.join(bullets(t, step, of) for t in texts)
            f.write(f'\\notespage{{{p}}}{{{title}}}{{{step}}}{{{of}}}'
                    f'{{{body}}}\n')
        f.write('\\end{document}\n')


if __name__ == '__main__':
    main()
